import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
const html = await readFile(new URL('../public/index.html', import.meta.url), 'utf8');
const script = await readFile(new URL('../public/app.js', import.meta.url), 'utf8');
for (const offer of ['29700','59940']) test(`popup and copy flow ${offer}`, async () => {
  const dom = new JSDOM(html, { url: `https://example.com/checkout/${offer}`, runScripts: 'outside-only' });
  const { window } = dom;
  const doc = window.document;
  const dialog = doc.querySelector('dialog');
  dialog.showModal = () => { dialog.open = true; };
  dialog.close = () => { dialog.open = false; };
  let calls = 0, copied;
  window.fetch = async (_url, options) => { calls++; assert.equal(JSON.parse(options.body).offer, offer); return { ok: true, json: async () => ({ amount: Number(offer), code: '000201TEST', qrImage: 'data:image/png;base64,TEST' }) }; };
  Object.defineProperty(window.navigator, 'clipboard', { value: { writeText: async value => { copied = value; } } });
  window.eval(script);
  for (const [id,value] of Object.entries({ email:'test@example.com', 'email-confirm':'test@example.com', name:'Cliente Teste', document:'52998224725', phone:'11999999999' })) doc.getElementById(id).value = value;
  const submit = () => doc.querySelector('form').dispatchEvent(new window.Event('submit', { cancelable:true }));
  submit(); submit();
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(calls,1);
  assert.equal(dialog.open,true);
  assert.equal(doc.querySelector('#pix-code').value,'000201TEST');
  assert.equal(doc.querySelector('#qr').hidden,false);
  doc.querySelector('#copy').click();
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(copied,'000201TEST');
  assert.match(doc.querySelector('#copy-status').textContent,/copiado/);
  doc.querySelector('#close').click();
  assert.equal(dialog.open,false);
  doc.querySelector('#open-pix').click();
  assert.equal(dialog.open,true);
  assert.equal(calls,1);
  dom.window.close();
});
